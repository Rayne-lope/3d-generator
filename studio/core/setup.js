// Engine setup data for markers: attachments (k.attach) and collision (k.collider /
// meta.collision). A GLB cannot carry Roblox Attachments or collision settings, so they are
// exported next to it:
//   <item>.setup.json    the data, in the file's units (every profile)
//   <item>.setup.rbxmx   Roblox: a ModuleScript that applies it to the imported model

import crypto from 'node:crypto';
import * as THREE from 'three';

const r5 = (v) => +v.toFixed(5);

/** True when an item has anything to set up in an engine. */
export function hasSetup(report) {
  return !!(report.attachments?.length || report.colliders?.length || report.collision === 'none');
}

/** Rotation quaternion → the three axis vectors of the rotated frame. */
function axes(rotation) {
  const m = new THREE.Matrix4().makeRotationFromQuaternion(new THREE.Quaternion(...rotation));
  const x = new THREE.Vector3();
  const y = new THREE.Vector3();
  const z = new THREE.Vector3();
  m.extractBasis(x, y, z);
  return { x: x.toArray().map(r5), y: y.toArray().map(r5), z: z.toArray().map(r5) };
}

/**
 * Setup data of a build report, in the report's file units (studs for Roblox).
 * Positions are relative to the asset origin; `bounds` and `meshes` let an engine script find
 * that origin on the imported model.
 */
export function setupData(report) {
  const { min, max } = report.bounds;
  const size = min.map((v, i) => r5(max[i] - v));
  return {
    schema: 1,
    item: report.id,
    title: report.title,
    profile: report.profile.id,
    units: { name: report.profile.units.name, perMeter: report.profile.units.perMeter },
    axes: { up: '+Y', front: '+Z', forward: 'the direction an attachment points (its look direction)' },
    size,
    maxSize: Math.max(...size),
    bounds: { min, max, center: min.map((v, i) => r5((v + max[i]) / 2)) },
    meshes: (report.meshBounds || []).map((m) => ({ node: m.node, center: m.center, size: m.size })),
    collision: report.collision || 'default',
    colliders: (report.colliders || []).map((c) => ({ name: c.name, node: c.node, shape: c.shape, size: c.size, position: c.position, rotation: c.rotation, ...axes(c.rotation) })),
    attachments: (report.attachments || []).map((a) => ({ name: a.name, node: a.node, position: a.position, forward: a.forward, up: a.up, rotation: a.rotation })),
  };
}

/** A JS value as a Lua table literal. */
export function luaValue(v, indent = '') {
  const next = `${indent}\t`;
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : '0';
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== 'object' || x === null)) return `{ ${v.map((x) => luaValue(x)).join(', ')} }`;
    return `{\n${v.map((x) => `${next}${luaValue(x, next)},`).join('\n')}\n${indent}}`;
  }
  const entries = Object.entries(v).filter(([, x]) => x !== undefined);
  return `{\n${entries.map(([k, x]) => `${next}${/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`} = ${luaValue(x, next)},`).join('\n')}\n${indent}}`;
}

/**
 * Luau ModuleScript that applies setup data to an imported model. It only uses scriptable
 * API (Parts, Attachments, CanCollide), and it refuses to run when the imported model does
 * not have the expected size.
 */
export function assetSetupLua(data) {
  const lua = {
    item: data.item,
    units: data.units.name,
    size: data.size,
    maxSize: data.maxSize,
    center: data.bounds.center,
    meshes: data.meshes.map((m) => ({ node: m.node, center: m.center })),
    collision: data.collision,
    colliders: data.colliders.map((c) => ({ name: c.name, node: c.node, shape: c.shape, size: c.size, position: c.position, x: c.x, y: c.y, z: c.z })),
    attachments: data.attachments.map((a) => ({ name: a.name, node: a.node, position: a.position, forward: a.forward, up: a.up })),
  };
  return `-- AssetSetup for "${data.item}" (generated by AI 3D Asset Studio). Do not edit: export again.
--
-- A GLB cannot carry Roblox Attachments or collision settings, so this module adds them to
-- the model after File > Import 3D:
--   * collision: invisible Parts in a "Collision" folder; the visual MeshParts stop colliding
--   * attachments: named Attachments on the MeshPart they belong to; their LookVector is the
--     direction the attachment points (a muzzle's LookVector is the shooting direction)
--
-- Usage (command bar in Studio, or a script):
--   local AssetSetup = require(path.to.AssetSetup)
--   AssetSetup.apply(workspace["${data.item}"])
--
-- apply() first checks that the model has the exported size (so a wrong Scale Unit or a
-- changed model stops here instead of placing things wrong). Running it again replaces what
-- it made before. It returns { colliders, attachments, yaw, sizeError, matchedParts }.

local DATA = ${luaValue(lua)}

local AssetSetup = {}
AssetSetup.data = DATA

local TAG = "StudioSetup"
local SIZE_TOLERANCE = 0.03

local function v3(t)
	return Vector3.new(t[1], t[2], t[3])
end

local function absVector(v)
	return Vector3.new(math.abs(v.X), math.abs(v.Y), math.abs(v.Z))
end

-- Visual parts of the model (everything except what this module created).
local function visualParts(model)
	local parts = {}
	for _, inst in ipairs(model:GetDescendants()) do
		if inst:IsA("BasePart") and not inst:GetAttribute(TAG) then
			table.insert(parts, inst)
		end
	end
	return parts
end

-- The part exported from glTF node \`node\`: same name, or the name followed by "_..."
-- (a node with several materials is split into one MeshPart per material).
local function findPart(parts, node)
	for _, part in ipairs(parts) do
		if part.Name == node then
			return part
		end
	end
	local prefix = node .. "_"
	for _, part in ipairs(parts) do
		if string.sub(part.Name, 1, #prefix) == prefix then
			return part
		end
	end
	return nil
end

local function cleanup(model)
	for _, inst in ipairs(model:GetDescendants()) do
		if inst:GetAttribute(TAG) then
			inst:Destroy()
		end
	end
end

-- The CFrame that maps asset space (the exported file's coordinates) to the world.
-- The importer may turn the model around the vertical axis, so the four quarter turns are
-- tried: the size must fit, and the positions of the MeshParts pick the right one.
local function solveFrame(model, parts)
	local boxCFrame, boxSize = model:GetBoundingBox()
	local size = v3(DATA.size)
	local center = v3(DATA.center)
	local best = nil
	for _, yaw in ipairs({ 0, 90, 180, 270 }) do
		local turn = CFrame.Angles(0, math.rad(yaw), 0)
		local sizeError = (boxSize - absVector(turn:VectorToWorldSpace(size))).Magnitude / DATA.maxSize
		local frame = boxCFrame * turn * CFrame.new(-center)
		local matched = 0
		local offset = 0
		for _, mesh in ipairs(DATA.meshes) do
			local part = findPart(parts, mesh.node)
			if part then
				matched = matched + 1
				offset = offset + ((frame * v3(mesh.center)) - part.Position).Magnitude / DATA.maxSize
			end
		end
		local score = sizeError + (matched > 0 and offset / matched or 0)
		if not best or score < best.score - 1e-6 then
			best = { score = score, yaw = yaw, frame = frame, sizeError = sizeError, matched = matched, boxSize = boxSize }
		end
	end
	return best
end

function AssetSetup.apply(model)
	assert(typeof(model) == "Instance" and model:IsA("Model"), "AssetSetup.apply: pass the imported Model")
	cleanup(model)
	local parts = visualParts(model)
	assert(#parts > 0, "AssetSetup.apply: the model has no parts")
	local solved = solveFrame(model, parts)
	if solved.sizeError > SIZE_TOLERANCE then
		error(string.format(
			"AssetSetup(%s): the model is %.3f x %.3f x %.3f %ss but the export is %.3f x %.3f x %.3f. Import with Scale Unit = Stud and do not resize the model before running this.",
			DATA.item, solved.boxSize.X, solved.boxSize.Y, solved.boxSize.Z, DATA.units, DATA.size[1], DATA.size[2], DATA.size[3]
		), 2)
	end
	local frame = solved.frame

	local anchored = false
	for _, part in ipairs(parts) do
		if part.Anchored then
			anchored = true
		end
	end

	if DATA.collision ~= "default" then
		for _, part in ipairs(parts) do
			part.CanCollide = false
		end
	end

	local colliders = 0
	if #DATA.colliders > 0 then
		local folder = Instance.new("Folder")
		folder.Name = "Collision"
		folder:SetAttribute(TAG, true)
		folder.Parent = model
		for _, c in ipairs(DATA.colliders) do
			local part = Instance.new("Part")
			part.Name = c.name
			part:SetAttribute(TAG, true)
			local cf = frame * CFrame.fromMatrix(v3(c.position), v3(c.x), v3(c.y), v3(c.z))
			if c.shape == "sphere" then
				part.Shape = Enum.PartType.Ball
				part.Size = Vector3.new(c.size[1] * 2, c.size[1] * 2, c.size[1] * 2)
			elseif c.shape == "cylinder" then
				-- Roblox cylinders run along the part's X axis; the exported one runs along Y.
				part.Shape = Enum.PartType.Cylinder
				part.Size = Vector3.new(c.size[2], c.size[1] * 2, c.size[1] * 2)
				cf = cf * CFrame.Angles(0, 0, math.rad(90))
			else
				part.Shape = Enum.PartType.Block
				part.Size = v3(c.size)
			end
			part.CFrame = cf
			part.Transparency = 1
			part.CastShadow = false
			part.Massless = true
			part.CanCollide = true
			part.Anchored = anchored
			part.Parent = folder
			if not anchored then
				local weld = Instance.new("WeldConstraint")
				weld.Part0 = findPart(parts, c.node) or parts[1]
				weld.Part1 = part
				weld.Parent = part
			end
			colliders = colliders + 1
		end
	end

	local attachments = 0
	for _, a in ipairs(DATA.attachments) do
		local owner = findPart(parts, a.node) or parts[1]
		local attachment = Instance.new("Attachment")
		attachment.Name = a.name
		attachment:SetAttribute(TAG, true)
		attachment.Parent = owner
		local position = frame * v3(a.position)
		local forward = frame:VectorToWorldSpace(v3(a.forward))
		local up = frame:VectorToWorldSpace(v3(a.up))
		attachment.WorldCFrame = CFrame.lookAt(position, position + forward, up)
		attachments = attachments + 1
	end

	model:SetAttribute("StudioSetupItem", DATA.item)
	local result = { colliders = colliders, attachments = attachments, yaw = solved.yaw, sizeError = solved.sizeError, matchedParts = solved.matched }
	print(string.format("AssetSetup(%s): %d collider(s), %d attachment(s); model turned %d deg, %d of %d mesh part(s) matched", DATA.item, colliders, attachments, solved.yaw, solved.matched, #DATA.meshes))
	return result
end

return AssetSetup
`;
}

/**
 * The same module as one chunk for Studio's command bar: paste it and press Enter, nothing has
 * to be inserted first. It applies the setup to the selected Model, or to the model named
 * after the item in Workspace. Comments are stripped, so it still runs if the command bar
 * joins the lines.
 */
export function assetSetupCommand(data) {
  const body = assetSetupLua(data)
    .split('\n')
    .filter((line) => line.trim() && !line.trim().startsWith('--'))
    .join('\n');
  return `local AssetSetup = (function()
${body}
end)()
local selected = game:GetService("Selection"):Get()[1]
local model = (selected and selected:IsA("Model")) and selected or workspace:FindFirstChild(${JSON.stringify(data.item)})
assert(model, "AssetSetup: select the imported model (or name it ${data.item}) and run this again")
AssetSetup.apply(model)
`;
}

/** A stable GUID for a script, in the form Studio writes ({XXXXXXXX-XXXX-XXXX-XXXX-XXXXXXXXXXXX}). */
function scriptGuid(seed) {
  const h = crypto.createHash('sha1').update(seed).digest('hex').toUpperCase();
  return `{${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}}`;
}

const xml = (s) => String(s).replace(/[&<>"]/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[ch]);
const cdata = (s) => `<![CDATA[${s.replaceAll(']]>', ']]]]><![CDATA[>')}]]>`;

/** Roblox XML model: Folder "<item> setup" with the AssetSetup ModuleScript. */
export function setupRbxmx(data) {
  return `<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">
	<External>null</External>
	<External>nil</External>
	<Item class="Folder" referent="RBX0">
		<Properties>
			<string name="Name">${xml(`${data.item} setup`)}</string>
		</Properties>
		<Item class="ModuleScript" referent="RBX1">
			<Properties>
				<Content name="LinkedSource"><null></null></Content>
				<string name="Name">AssetSetup</string>
				<string name="ScriptGuid">${scriptGuid(`AssetSetup:${data.item}`)}</string>
				<ProtectedString name="Source">${cdata(assetSetupLua(data))}</ProtectedString>
				<BinaryString name="Tags"></BinaryString>
			</Properties>
		</Item>
	</Item>
</roblox>
`;
}
